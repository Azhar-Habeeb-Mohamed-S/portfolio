#!/usr/bin/env node
"use strict";

/**
 * Generates supabase-config.js from environment variables.
 *
 * Local:  copy .env.example to .env, fill in the two values, run `npm run config`.
 * Deploy: GitHub Actions reads the same values from repository secrets.
 *
 * When no values are present an empty config is written, so the site still
 * works with its per-browser localStorage like counter. No secrets are ever
 * committed.
 */

const fs = require("node:fs");
const path = require("node:path");

const root = path.join(__dirname, "..");
const envPath = path.join(root, ".env");

// Tiny .env reader (KEY=VALUE), so no dotenv dependency is needed.
if (fs.existsSync(envPath)) {
  for (const raw of fs.readFileSync(envPath, "utf8").split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith("#")) continue;
    const equals = line.indexOf("=");
    if (equals < 1) continue;
    const key = line.slice(0, equals).trim();
    const value = line
      .slice(equals + 1)
      .trim()
      .replace(/^["']|["']$/g, "");
    if (!(key in process.env)) process.env[key] = value;
  }
}

const url = process.env.SUPABASE_URL || "";
const anonKey = process.env.SUPABASE_ANON_KEY || "";

const output = `/* Generated by scripts/generate-config.js - do not edit by hand. */
window.AZHAR_SUPABASE = {
  url: ${JSON.stringify(url)},
  anonKey: ${JSON.stringify(anonKey)},
};
`;

fs.writeFileSync(path.join(root, "supabase-config.js"), output);

if (url && anonKey) {
  console.log("Supabase config generated from environment values.");
} else {
  console.log("No Supabase values found; generated empty config (local like counter).");
}
